def zib_aufgaben_nach_thema(thema):
    return [
        aufgabe
        for aufgabe in ZIB_AUFGABEN
        if aufgabe["thema"] == thema
    ]


def zib_aufgaben_nach_typ(typ):
    return [
        aufgabe
        for aufgabe in ZIB_AUFGABEN
        if aufgabe.get("typ") == typ
    ]


def zib_aufgaben_nach_unterthema(unterthema):
    return [
        aufgabe
        for aufgabe in ZIB_AUFGABEN
        if aufgabe["unterthema"] == unterthema
    ]